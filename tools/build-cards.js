// Builds cards.js from the open pokemon-tcg-data set files.
// Usage: node tools/build-cards.js <folder with sv3pt5.json, sv8pt5.json, swsh7.json, base1.json>
const fs = require('fs');
const path = require('path');

const SETS = ['sv3pt5', 'sv8pt5', 'swsh7', 'base1'];
const src = process.argv[2];
if (!src) throw new Error('pass the folder with the set json files');

const rarities = [];
const out = {};
for (const id of SETS) {
  const cards = JSON.parse(fs.readFileSync(path.join(src, id + '.json'), 'utf8'));
  out[id] = cards.map(c => {
    const rar = c.rarity || 'Common';
    let r = rarities.indexOf(rar);
    if (r < 0) r = rarities.push(rar) - 1;
    if (/[|;]/.test(c.name)) throw new Error('bad name ' + c.name);
    return `${c.number}|${c.name}|${r}`;
  }).join(';');
  console.log(id, cards.length);
}
const js = `// Generated by tools/build-cards.js. "number|name|rarity index" per card.\n` +
  `window.RARITIES = ${JSON.stringify(rarities)};\nwindow.CARD_DATA = ${JSON.stringify(out, null, 1)};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'cards.js'), js);
console.log('rarities', rarities.join(', '));
